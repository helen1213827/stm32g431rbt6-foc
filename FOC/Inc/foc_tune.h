#ifndef __FOC_TUNE_H
#define __FOC_TUNE_H

/* ===================================================================
 *         ★★★  FOC 整定参数总表 —— 要改参数只改这个文件  ★★★
 * ===================================================================
 *
 * 上电时用这里的默认值; 运行中可以用串口在线改，改完发 `param` 看实时值。
 *
 *   串口命令                    对应本表的哪一行
 *   ----------------------------------------------------------
 *   rs / ls / flux              电机参数
 *   bw                          电流环带宽
 *   ff / vbus / dtc             前馈 / 母线 / 死区补偿
 *   spdkp / spdki / iql         速度环 kp / ki / 最大 iq
 *   spdf                        测速低通 (ms)
 *   poskp / poski / poskd       位置环 kp / ki / kd
 *   posv / posacc / posjerk     位置参考轨迹 速度/加速度/加加速度
 *
 * ---------------------------------------------------------------
 *  实测经验值 (不是理论值，是这台机器上试出来的)
 * ---------------------------------------------------------------
 *   spdkp    0.01 ~ 0.1        > 0.1 会因【测速噪声】明显振动
 *   spdki    ≈ 19 × spdkp² / 2  ★ kp 的平方关系，不是线性 ★
 *   iql      1.5               = 速度环输出限幅 (A)
 *   poskp    0.001 ~ 0.003     再大就来回摆
 *   posacc   ≤ 19 × iql ≈ 28   超过机器做不到 → 整段饱和 → 冲过头
 *
 * ---------------------------------------------------------------
 *  三条硬约束 —— 违反了必然振荡
 * ---------------------------------------------------------------
 *  1) 位置环比速度环慢。速度环 kp 上不去(噪声限制)，位置环就快不了。
 *  2) 速度环 kp 的上限由【测速噪声】决定，不是由稳定性决定:
 *       力矩噪声 = spdkp × σ_ω
 *     先用 `dbg 2` 看静止时 spdw=[min max] 的跨度，那跨度就是 σ_ω 的量级。
 *  3) 所有"加速度"参数 ≤ 机器实际能力 a_max = (Kt/J) × iql ≈ 19 × iql
 * =================================================================== */

/* ---------------- 电机参数 ---------------- */
#define FOC_TUNE_RS        5.0f      /* 相电阻 (Ω): 实测线间 10Ω ÷ 2 (星形) */
#define FOC_TUNE_LS        1.0e-3f   /* 相电感 (H): 测不出, 取 4310 云台经典值 */
#define FOC_TUNE_FLUX      0.0f      /* 磁链 (Wb): 0 = 不补偿反电动势 */

/* ---------------- 电流环 (10 kHz) ---------------- */
/* ωc (rad/s)。Kp = ωc·L, Ki = ωc·R 自动算出来, 不用手填。
 * 400 ≈ 64Hz; 提到 800 可加快电流响应, 但 L 是猜的, 提太快可能振。 */
#define FOC_TUNE_CUR_BW    400.0f

/* ---------------- 速度环 (1 kHz) ---------------- */
#define FOC_TUNE_SPD_KP    0.01f     /* ★ 你要找的就是这个 ★ */
#define FOC_TUNE_SPD_KI    0.1f
#define FOC_TUNE_SPD_IQL   1.5f      /* 输出限幅 = 最大 iq (A) */
#define FOC_TUNE_SPD_LPF   15.0f     /* 测速低通时间常数 (ms), 0 = 关 */

/* ---------------- 位置环 (100 Hz) ---------------- */
#define FOC_TUNE_POS_KP    0.002f    /* 单位 (rad/s) 每 count */
#define FOC_TUNE_POS_KI    0.002f
#define FOC_TUNE_POS_KD    0.0f
#define FOC_TUNE_POS_VMAX  5.0f      /* 速度指令上限 (rad/s) */
#define FOC_TUNE_POS_ACC   15.0f     /* 参考轨迹加速度 (rad/s²) */
#define FOC_TUNE_POS_JERK  300.0f    /* 参考轨迹加加速度 (rad/s³) */

/* ---------------- 其它 ---------------- */
#define FOC_TUNE_FF        0.0f      /* dq 解耦/反电动势前馈 0~1 */
#define FOC_TUNE_VBUS      12.0f     /* 母线电压 (V) */
#define FOC_TUNE_DTC       0.0f      /* 死区补偿占空比 (0 = 关) */

/* 测速滑窗长度 (ms)。
 * 它是数组长度 (编译期常量), 不能用串口命令改。
 * 窗口越短噪声越大: 1 LSB 折算的速度 = (2π/65536)/窗口
 *   4ms → 2.4 rad/s    10ms → 0.96 rad/s    20ms → 0.48 rad/s
 * 不要为了"减少滞后"去裁短它 —— 那只会放大噪声。 */
#define FOC_TUNE_SPD_WIN_MS  10U

#endif
